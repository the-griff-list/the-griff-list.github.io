-- Run this once in Supabase SQL Editor to enable the public confirmed-tip wall.
create table if not exists public.confirmed_tips (
  id bigint generated by default as identity primary key,
  display_name text not null default 'Anonymous Rocker' check (char_length(display_name) <= 50),
  amount_cad numeric(10,2) not null check (amount_cad > 0),
  requested_song text null check (char_length(coalesce(requested_song,'')) <= 200),
  confirmed boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.confirmed_tips enable row level security;
drop policy if exists "Public can read confirmed tip wall entries" on public.confirmed_tips;
create policy "Public can read confirmed tip wall entries" on public.confirmed_tips for select to anon, authenticated using (confirmed = true);
drop policy if exists "Admin manages confirmed tips" on public.confirmed_tips;
create policy "Admin manages confirmed tips" on public.confirmed_tips for all to authenticated using (auth.uid() = '7c4c9232-2c28-47f3-a00a-a371ed23cef5'::uuid) with check (auth.uid() = '7c4c9232-2c28-47f3-a00a-a371ed23cef5'::uuid);

-- Explicit API grants; row-level security still controls which rows each role can access.
grant select on public.confirmed_tips to anon, authenticated;
grant insert, update, delete on public.confirmed_tips to authenticated;
grant usage, select on sequence public.confirmed_tips_id_seq to authenticated;
