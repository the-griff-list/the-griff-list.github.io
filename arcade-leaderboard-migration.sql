-- The Grifflist: public Guitar Pick Panic leaderboard
-- Run once in Supabase SQL Editor. Scores are casual/unsupervised and are not anti-cheat verified.
create table if not exists public.arcade_leaderboard (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 24),
  score integer not null check (score between 0 and 150),
  created_at timestamptz not null default now()
);

alter table public.arcade_leaderboard enable row level security;

drop policy if exists "Anyone can view arcade leaderboard" on public.arcade_leaderboard;
create policy "Anyone can view arcade leaderboard"
on public.arcade_leaderboard for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can submit a reasonable arcade score" on public.arcade_leaderboard;
create policy "Anyone can submit a reasonable arcade score"
on public.arcade_leaderboard for insert
to anon, authenticated
with check (
  char_length(trim(player_name)) between 1 and 24
  and score between 0 and 150
);

create index if not exists arcade_leaderboard_score_created_idx
on public.arcade_leaderboard (score desc, created_at asc);

grant select, insert on public.arcade_leaderboard to anon, authenticated;
grant usage, select on sequence public.arcade_leaderboard_id_seq to anon, authenticated;
