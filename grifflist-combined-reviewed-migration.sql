-- Public-safe aggregate only: never returns requester names, notes, or request IDs.
-- Unknown range values return no rows instead of silently returning all-time results.
create or replace function public.get_crowd_favourites(p_range text default 'all')
returns table (
  song_title text,
  artist_name text,
  request_count bigint,
  played_count bigint
)
language sql
stable
security definer
set search_path = ''
as $function$
  select r.song_title,
         coalesce(r.artist_name, '') as artist_name,
         count(*)::bigint as request_count,
         count(*) filter (where r.status = 'Played')::bigint as played_count
  from public.song_requests as r
  where nullif(trim(r.song_title), '') is not null
    and coalesce(p_range, 'all') in ('all', 'month', 'show')
    and (
      coalesce(p_range, 'all') <> 'month'
      or r.created_at >= date_trunc('month', now())
    )
    and (
      coalesce(p_range, 'all') <> 'show'
      or exists (
        select 1
        from public.live_show_settings as s
        where s.id = 1
          and s.session_started_at is not null
          and r.created_at >= s.session_started_at
      )
    )
  group by r.song_title, coalesce(r.artist_name, '')
  order by count(*) desc, lower(r.song_title) asc
  limit 100;
$function$;

revoke all on function public.get_crowd_favourites(text) from public;
grant execute on function public.get_crowd_favourites(text) to anon, authenticated;

