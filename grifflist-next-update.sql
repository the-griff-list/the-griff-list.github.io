-- Public-safe aggregate only: never returns requester names, notes, or request IDs.
create or replace function public.get_crowd_favourites(p_range text default 'all')
returns table(song_title text, artist_name text, request_count bigint, played_count bigint)
language sql stable security definer set search_path = public
as $$
  select r.song_title,
         coalesce(r.artist_name, '') as artist_name,
         count(*)::bigint as request_count,
         count(*) filter (where r.status = 'Played')::bigint as played_count
  from public.song_requests r
  where nullif(trim(r.song_title), '') is not null
    and (coalesce(p_range, 'all') <> 'month' or r.created_at >= date_trunc('month', now()))
    and (coalesce(p_range, 'all') <> 'show' or r.created_at >= coalesce((select session_started_at from public.live_show_settings where id = 1), '-infinity'::timestamptz))
  group by r.song_title, coalesce(r.artist_name, '')
  order by count(*) desc, lower(r.song_title) asc
  limit 100;
$$;
revoke all on function public.get_crowd_favourites(text) from public;
grant execute on function public.get_crowd_favourites(text) to anon, authenticated;


-- Privacy-friendly request status: visitors receive an unguessable token for their own request.
alter table public.song_requests add column if not exists tracking_token uuid;
create unique index if not exists song_requests_tracking_token_unique on public.song_requests(tracking_token) where tracking_token is not null;
create or replace function public.get_my_request_status(p_tracking_token uuid)
returns table(song_title text, artist_name text, status text)
language sql stable security definer set search_path = public
as $$
  select r.song_title, coalesce(r.artist_name,''), coalesce(r.status,'Received')
  from public.song_requests r
  where r.tracking_token = p_tracking_token
  limit 1;
$$;
revoke all on function public.get_my_request_status(uuid) from public;
grant execute on function public.get_my_request_status(uuid) to anon, authenticated;

