-- The Grifflist: persistent request archive
-- Run once in Supabase SQL Editor. Does not delete or change live requests.
create table if not exists public.request_archive (
  archive_id bigint generated by default as identity primary key,
  request_id text unique,
  requester_name text,
  song_title text,
  artist_name text,
  note text,
  requested_at timestamptz,
  archived_at timestamptz not null default now()
);

alter table public.request_archive enable row level security;
drop policy if exists "Admin can read request archive" on public.request_archive;
create policy "Admin can read request archive"
  on public.request_archive for select to authenticated
  using (auth.uid() = '7c4c9232-2c28-47f3-a00a-a371ed23cef5'::uuid);

create or replace function public.archive_song_request()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.request_archive (request_id, requester_name, song_title, artist_name, note, requested_at)
  values (new.id::text, new.requester_name, new.song_title, new.artist_name, new.note, new.created_at)
  on conflict (request_id) do update set
    requester_name = excluded.requester_name,
    song_title = excluded.song_title,
    artist_name = excluded.artist_name,
    note = excluded.note,
    requested_at = excluded.requested_at;
  return new;
end;
$$;

revoke all on function public.archive_song_request() from public;
drop trigger if exists song_requests_archive_insert on public.song_requests;
create trigger song_requests_archive_insert
after insert on public.song_requests
for each row execute function public.archive_song_request();

-- Backfill existing requests so the archive includes requests already in the live table.
insert into public.request_archive (request_id, requester_name, song_title, artist_name, note, requested_at)
select id::text, requester_name, song_title, artist_name, note, created_at
from public.song_requests
on conflict (request_id) do nothing;
